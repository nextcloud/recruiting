namespace OCA\Recruiting\Imap;

/**
 * Header-based verdicts on an incoming mail: is it machine-generated
 * (bounce, autoresponder, mailing list), and does the receiving server's
 * authentication check say the sender is forged?
 */
class MailClassifier {
	/**
	 * Bounces, out-of-office replies, list traffic and other mail no person
	 * wrote (RFC 3834, RFC 3464, common vendor headers).
	 */
	public function isAutoGenerated(ParsedMail $mail): bool {
		$autoSubmitted = strtolower(trim(explode(';', $mail->header('auto-submitted'))[0]));
		if ($autoSubmitted !== '' && $autoSubmitted !== 'no') {
			return true;
		}
		if (in_array(strtolower(trim($mail->header('precedence'))), ['bulk', 'list', 'junk'], true)) {
			return true;
		}
		if (trim($mail->header('list-id')) !== '') {
			return true;
		}
		foreach (['x-autoreply', 'x-autorespond'] as $name) {
			$value = strtolower(trim($mail->header($name)));
			if ($value !== '' && $value !== 'no') {
				return true;
			}
		}
		$suppress = array_map(
			static fn (string $v): string => strtolower(trim($v)),
			explode(',', $mail->header('x-auto-response-suppress')),
		);
		if (in_array('all', $suppress, true) || in_array('oof', $suppress, true)) {
			return true;
		}
		if (preg_replace('/\s+/', '', $mail->header('return-path')) === '<>') {
			return true;
		}
		$local = strtolower(explode('@', $mail->fromEmail)[0]);
		if ($local === 'mailer-daemon' || $local === 'postmaster') {
			return true;
		}
		return $mail->contentType === 'multipart/report';
	}

	/**
	 * True when the topmost Authentication-Results header shows the From
	 * address is spoofed: DMARC failed, or SPF failed without any passing
	 * DKIM signature. No header means no verdict (false).
	 */
	public function isForged(ParsedMail $mail): bool {
		$results = $this->parseAuthenticationResults($mail->header('authentication-results'));
		if (in_array('fail', $results['dmarc'] ?? [], true)) {
			return true;
		}
		return in_array('fail', $results['spf'] ?? [], true)
			&& !in_array('pass', $results['dkim'] ?? [], true);
	}

	/**
	 * Parse an RFC 8601 Authentication-Results value into method => results.
	 * Comments (also nested) and quoted strings are removed first, so a
	 * semicolon inside them does not split a result; the leading authserv-id
	 * is dropped.
	 *
	 * @return array<string, list<string>> e.g. ['spf' => ['pass'], 'dkim' => ['fail', 'pass']]
	 */
	public function parseAuthenticationResults(string $value): array {
		$value = $this->stripCommentsAndQuotes($value);
		$segments = explode(';', $value);
		array_shift($segments);

		$results = [];
		foreach ($segments as $segment) {
			if (!preg_match('/^\s*([a-z0-9_-]+)(?:\/[0-9]+)?\s*=\s*([a-z0-9_-]+)/i', $segment, $m)) {
				continue;
			}
			$results[strtolower($m[1])][] = strtolower($m[2]);
		}
		return $results;
	}

	private function stripCommentsAndQuotes(string $value): string {
		$out = '';
		$depth = 0;
		$quoted = false;
		$length = strlen($value);
		for ($i = 0; $i < $length; $i++) {
			$char = $value[$i];
			if ($char === '\\' && ($quoted || $depth > 0)) {
				$i++;
				continue;
			}
			if ($quoted) {
				if ($char === '"') {
					$quoted = false;
				}
				continue;
			}
			if ($char === '(') {
				$depth++;
				continue;
			}
			if ($char === ')' && $depth > 0) {
				$depth--;
				continue;
			}
			if ($depth > 0) {
				continue;
			}
			if ($char === '"') {
				$quoted = true;
				$out .= '""';
				continue;
			}
			$out .= $char;
		}
		return $out;
	}
}
