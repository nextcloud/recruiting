namespace OCA\Recruiting\Tests\Unit;

use OCA\Recruiting\Imap\MailClassifier;
use OCA\Recruiting\Imap\MimeParser;
use OCA\Recruiting\Imap\ParsedMail;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\TestCase;

/**
 * Automatic-mail detection and the Authentication-Results verdict that
 * decide whether intake creates a candidate and sends an acknowledgement.
 */
class MailClassifierTest extends TestCase {
	private MailClassifier $classifier;

	protected function setUp(): void {
		$this->classifier = new MailClassifier();
	}

	private function mail(string $headerBlock, string $from = 'Jane Doe <jane@example.com>'): ParsedMail {
		return (new MimeParser())->parse(
			'From: ' . $from . "\r\n"
			. "To: jobs@company.com\r\n"
			. "Subject: Hello\r\n"
			. $headerBlock
			. "\r\n"
			. "Body\r\n",
		);
	}

	public static function automaticHeaders(): array {
		return [
			'auto-submitted auto-replied' => ["Auto-Submitted: auto-replied\r\n"],
			'auto-submitted auto-generated with params' => ["Auto-Submitted: auto-generated; type=bounce\r\n"],
			'precedence bulk' => ["Precedence: bulk\r\n"],
			'precedence list' => ["Precedence: List\r\n"],
			'precedence junk' => ["Precedence: junk\r\n"],
			'list-id' => ["List-Id: Jobs digest <jobs.lists.example.org>\r\n"],
			'x-autoreply' => ["X-Autoreply: yes\r\n"],
			'x-autorespond' => ["X-Autorespond: Out of office\r\n"],
			'x-auto-response-suppress all' => ["X-Auto-Response-Suppress: All\r\n"],
			'x-auto-response-suppress oof in list' => ["X-Auto-Response-Suppress: DR, OOF, AutoReply\r\n"],
			'null return path' => ["Return-Path: <>\r\n"],
			'null return path with space' => ["Return-Path: < >\r\n"],
			'delivery report' => ["Content-Type: multipart/report; report-type=delivery-status; boundary=\"b\"\r\n"],
		];
	}

	#[DataProvider('automaticHeaders')]
	public function testAutomaticMailIsDetected(string $headers): void {
		$this->assertTrue($this->classifier->isAutoGenerated($this->mail($headers)));
	}

	public static function humanHeaders(): array {
		return [
			'no special headers' => [''],
			'auto-submitted no' => ["Auto-Submitted: no\r\n"],
			'precedence normal' => ["Precedence: normal\r\n"],
			'x-autoreply no' => ["X-Autoreply: no\r\n"],
			'x-auto-response-suppress other values' => ["X-Auto-Response-Suppress: DR, RN\r\n"],
			'regular return path' => ["Return-Path: <jane@example.com>\r\n"],
			'multipart mixed' => ["Content-Type: multipart/mixed; boundary=\"b\"\r\n"],
		];
	}

	#[DataProvider('humanHeaders')]
	public function testHumanMailIsNotAutomatic(string $headers): void {
		$this->assertFalse($this->classifier->isAutoGenerated($this->mail($headers)));
	}

	public function testMailerDaemonAndPostmasterAreAutomatic(): void {
		$this->assertTrue($this->classifier->isAutoGenerated($this->mail('', 'Mail Delivery System <MAILER-DAEMON@mx.example.com>')));
		$this->assertTrue($this->classifier->isAutoGenerated($this->mail('', 'postmaster@example.com')));
		$this->assertFalse($this->classifier->isAutoGenerated($this->mail('', 'Post Master <post.master@example.com>')));
	}

	public function testParsesAGmailStyleHeader(): void {
		$results = $this->classifier->parseAuthenticationResults(
			'mx.google.com; dkim=pass header.i=@example.com header.s=sel header.b=abc;'
			. ' spf=pass (google.com: domain of jane@example.com designates 192.0.2.1 as permitted sender) smtp.mailfrom=jane@example.com;'
			. ' dmarc=pass (p=REJECT sp=REJECT dis=NONE) header.from=example.com',
		);
		$this->assertSame(['dkim' => ['pass'], 'spf' => ['pass'], 'dmarc' => ['pass']], $results);
	}

	public function testSemicolonsInCommentsAndQuotesDoNotSplit(): void {
		$results = $this->classifier->parseAuthenticationResults(
			'mx.example.com; spf=fail (sender; not (nested; really) permitted) smtp.mailfrom=a@b.c;'
			. ' dkim=pass reason="good; signature" header.d=b.c',
		);
		$this->assertSame(['spf' => ['fail'], 'dkim' => ['pass']], $results);
	}

	public function testVersionedAuthservIdAndMethodVersionAndCase(): void {
		$results = $this->classifier->parseAuthenticationResults('mx.example.com 1; DKIM/1=FAIL header.d=x; dkim=Pass header.d=y; SPF = SoftFail');
		$this->assertSame(['dkim' => ['fail', 'pass'], 'spf' => ['softfail']], $results);
	}

	public function testNoneAndEmptyHeadersYieldNoResults(): void {
		$this->assertSame([], $this->classifier->parseAuthenticationResults('mx.example.com; none'));
		$this->assertSame([], $this->classifier->parseAuthenticationResults(''));
		$this->assertSame([], $this->classifier->parseAuthenticationResults('garbage without any structure'));
	}

	public function testTheAuthservIdIsNeverTakenForAResult(): void {
		$this->assertSame([], $this->classifier->parseAuthenticationResults('dmarc=fail'));
	}

	public static function authenticationVerdicts(): array {
		return [
			'no header' => ['', false],
			'all pass' => ["Authentication-Results: mx.example.com; spf=pass; dkim=pass; dmarc=pass\r\n", false],
			'dmarc fail' => ["Authentication-Results: mx.example.com; spf=pass; dkim=pass; dmarc=fail\r\n", true],
			'spf fail without dkim' => ["Authentication-Results: mx.example.com; spf=fail smtp.mailfrom=jane@example.com\r\n", true],
			'spf fail with dkim fail' => ["Authentication-Results: mx.example.com; spf=fail; dkim=fail\r\n", true],
			'spf fail rescued by dkim pass' => ["Authentication-Results: mx.example.com; spf=fail; dkim=pass\r\n", false],
			'spf softfail' => ["Authentication-Results: mx.example.com; spf=softfail\r\n", false],
			'dmarc none' => ["Authentication-Results: mx.example.com; dmarc=none\r\n", false],
			'only the topmost header counts' => [
				"Authentication-Results: mx.company.com; spf=pass; dmarc=pass\r\n"
				. "Authentication-Results: relay.example.net; dmarc=fail\r\n",
				false,
			],
			'forged lower header does not rescue' => [
				"Authentication-Results: mx.company.com; dmarc=fail\r\n"
				. "Authentication-Results: mx.company.com; dmarc=pass\r\n",
				true,
			],
		];
	}

	#[DataProvider('authenticationVerdicts')]
	public function testForgedSenderVerdict(string $headers, bool $forged): void {
		$this->assertSame($forged, $this->classifier->isForged($this->mail($headers)));
	}
}
